#!/usr/bin/env python3
"""Regenerate Flik's animation catalogue from the retail work copy.

Reads ``bugs.exe`` and the player-model ``.ANM`` files under a full-disc work
copy (never ``originals/``), joins them with the authored labels in
``config/animation/pc-flik-animations.json`` and writes metadata only:
offsets, counts, frame scripts and labels, never animation payload bytes.

    scripts/flik-animation-catalog.py            # write reports/animation/
    scripts/flik-animation-catalog.py --check    # fail if the reports are stale
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from reimplementation.ablpc import flik_animation as fa  # noqa: E402

DISC = ROOT/'work/copies/BUGS_PC-full-disc/PC/BUGS'
OUT = ROOT/'reports/animation'


def table(catalog: dict) -> str:
    slots = {row['slot']: row for row in catalog['slots']}
    lines = [
        '# Flik animation catalogue (generated)',
        '',
        'Generated by `scripts/flik-animation-catalog.py` from retail `bugs.exe` '
        f"`{catalog['inputs']['executable_sha256'][:12]}…` and `CHARS/FLICK.ANM` "
        f"`{catalog['inputs']['flick_anm_sha256'][:12]}…`. Do not edit by hand; "
        'labels come from `config/animation/pc-flik-animations.json`. The '
        'human reference is the Vault note `PC Flik animation catalog`.',
        '',
        '## Action states (`0x0059D998`)',
        '',
        '| State | Name | Status | ANM slot(s) | Steps | End | Speed | Steps-sound | Trigger |',
        '|---|---|---|---|---|---|---|---|---|',
    ]
    for row in catalog['states']:
        layers = (str(row['slot_a']) if row['slot_a'] == row['slot_b']
                  else f"{row['slot_a']} upper + {row['slot_b']} lower")
        end = ('end → state 0' if row['end'] == 'end'
               else 'hold last frame' if row['loop_to'] == row['steps']-1
               else 'loop' if row['loop_to'] == 0
               else f"loop from step {row['loop_to']}")
        steps = ', '.join(f"{e['step']}{e['side'][0].upper()}" for e in row['footstep_events'])
        lines.append(f"| `{row['hex']}` | {row['name']} | {row['status']} | {layers} | "
                     f"{row['steps']} | {end} | {row['speed']} | {steps or '—'} | "
                     f"{row['trigger']} |")
    lines += ['', '## ANM slots (`CHARS/FLICK.ANM`)', '',
              '| Slot | Name | Status | Frames | s @30 | Body | Used by |',
              '|---|---|---|---|---|---|---|']
    for slot in range(catalog['slot_count']):
        row = slots[slot]
        if not row['present']:
            lines.append(f"| {slot} | {row['name']} | {row['status']} | absent | — | — | "
                         f"{'; '.join(row['used_by']) or '—'} |")
            continue
        lines.append(f"| {slot} | {row['name']} | {row['status']} | {row['frames']} | "
                     f"{row['seconds_at_30']} | {row['layer']} | "
                     f"{'; '.join(row['used_by']) or 'no reference'} |")
    lines += ['', '## Player-model variants', '',
              '| File | `0x00861C84` | Parts | Absent slots | Frame-count mismatches |',
              '|---|---|---|---|---|']
    for row in catalog['model_variants']:
        levels = row['selected_by_0x00861C84']
        lines.append(f"| `{row['path']}` | {levels if levels == 'default' else ', '.join(map(str, levels))} | "
                     f"{', '.join(map(str, row['part_counts']))} | "
                     f"{', '.join(map(str, row['absent_slots']))} | "
                     f"{', '.join(map(str, row['frame_count_mismatches'])) or 'none'} |")
    for model in catalog['other_flik_models']:
        lines += ['', f"## Non-player model `{model['path']}` (entity type {model['entity_type']:#04x})", '',
                  model.get('summary', 'Behaviour labels pending.'), '',
                  '| Slot | Name | Status | Frames | s @30 | Trigger |', '|---|---|---|---|---|---|']
        for row in model['slots']:
            lines.append(f"| {row['slot']} | {row.get('name', 'unlabelled')} | "
                         f"{row.get('status', 'unknown')} | {row.get('frames', 'absent')} | "
                         f"{row.get('seconds_at_30', '—')} | {row.get('trigger', '—')} |")
    lines += ['', '## Notes', ''] + [f'- {note}' for note in catalog['notes']]
    return '\n'.join(lines)+'\n'


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--disc', type=Path, default=DISC,
                        help='work-copy directory holding bugs.exe and CD/')
    parser.add_argument('--out', type=Path, default=OUT)
    parser.add_argument('--check', action='store_true',
                        help='compare with the existing reports instead of writing')
    args = parser.parse_args()
    if 'originals' in args.disc.resolve().parts:
        parser.error('read a work copy, never originals/')
    cd = args.disc/'CD'
    catalog = fa.catalog((args.disc/'bugs.exe').read_bytes(),
                         (cd/'CHARS/FLICK.ANM').read_bytes(),
                         variant_rows=fa.variants(cd), other_rows=fa.other_models(cd))
    outputs = {
        args.out/'flik-animation-catalog.json': json.dumps(catalog, indent=2)+'\n',
        args.out/'flik-animation-catalog.md': table(catalog),
    }
    if args.check:
        stale = [str(p) for p, text in outputs.items() if not p.exists() or p.read_text() != text]
        if stale:
            print('stale: '+', '.join(stale), file=sys.stderr)
            return 1
        print('Flik animation catalogue is current')
        return 0
    args.out.mkdir(parents=True, exist_ok=True)
    for path, text in outputs.items():
        path.write_text(text)
        print(path)
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
